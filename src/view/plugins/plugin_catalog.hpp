#ifndef PLUGIN_CATALOG_HPP
#define PLUGIN_CATALOG_HPP

#include <QString>

#include <functional>
#include <memory>
#include <optional>
#include <string>
#include <vector>

namespace noteahead {

class AudioService;
class Effect;
class Device;
class DeviceDialogModel;
class DeviceService;

//! What the UI knows of each effect and device that registers itself: its gallery entry, its dialog
//! and, for a device, the controller its dialog binds to.
//!
//! Filled by the register<Name><Kind>View() functions in the plugin folders, whose calls are
//! generated by src/plugins/CMakeLists.txt. Everything that used to keep a list of plugins reads it
//! from here instead.
class PluginCatalog
{
public:
    //! The gallery's grouping, shown after each name. Translated where it is shown.
    enum class EffectCategory
    {
        Dynamics,
        EqAndFilter,
        Distortion,
        Modulation,
        Space,
        Stereo,
        Utility,
        Meters
    };

    enum class DeviceCategory
    {
        Synths,
        Keys,
        StringsAndVoice,
        Drums,
        Samplers,
        Mixers,
        Modulators
    };

    //! What a summary may need beyond the effect itself.
    struct SummaryContext
    {
        //! The device in a slot, for naming a side-chain source. Null for an empty slot.
        std::function<std::shared_ptr<noteahead::Device>(size_t slot)> device;
    };

    struct Effect
    {
        //! The gallery name. Effect names are not translated.
        QString name;
        std::string typeId;
        //! Effect::type(), which is what a rack slot reports.
        QString type;
        EffectCategory category;
        //! The dialog's file name, beside the other dialogs in the QML module.
        QString dialogFile;
        //! The one-line parameter summary the rack lists show, or empty when it cannot be made.
        std::function<QString(const std::shared_ptr<noteahead::Effect> & effect, const SummaryContext & context)> summary {};
        //! Registers the effect's own QML types, such as its EffectDialogModel, if it has any.
        std::function<void()> registerQmlTypes {};
    };

    using DeviceDialogModelS = std::shared_ptr<DeviceDialogModel>;
    using DeviceServiceS = std::shared_ptr<DeviceService>;

    //! What a controller may need once the application is up, given to Device::connectServices.
    struct Services
    {
        DeviceServiceS deviceService;
        std::shared_ptr<AudioService> audioService;
    };

    struct Device
    {
        //! The gallery name. Device names are not translated.
        QString name;
        std::string typeId;
        DeviceCategory category;
        //! The dialog's file name, beside the other dialogs in the QML module.
        QString dialogFile;
        //! The context property the dialog reaches its controller by.
        QString controllerProperty;
        //! Makes the one controller the device type's dialogs share.
        std::function<DeviceDialogModelS(const DeviceServiceS & deviceService)> createDialogModel;
        //! Hands the controller the services that do not exist yet when it is made, if it needs any.
        std::function<void(DeviceDialogModel & controller, const Services & services)> connectServices {};
        //! Registers the device's own QML types, if it has any.
        std::function<void()> registerQmlTypes {};
    };

    static void addEffect(Effect effect);
    static void addDevice(Device device);

    static const std::vector<Effect> & effects();
    static const std::vector<Device> & devices();

    static std::optional<Effect> effectByType(const QString & type);
    static std::optional<Device> deviceByTypeId(const std::string & typeId);

private:
    //! Generated; see src/plugins/CMakeLists.txt.
    static void registerEffectPlugins();
    static void registerDevicePlugins();

    static void ensureRegistered();
};

} // namespace noteahead

#endif // PLUGIN_CATALOG_HPP
